#!/usr/bin/env python3
"""Write A1222 boot.cmd variants that do not depend on USB enumeration order.

The saved firmware startup command sources /boot.scr from usb 0:1. With a second
stick (PNY) attached, that may be the PNY. The same boot.scr goes on both sticks'
FAT partitions; it finds the root stick by a marker file only the SanDisk carries,
then loads kernel and DTB from that stick. Only constructs this board has already
run are used (if/fatload/iminfo/setenv/bootm, no for-loops or variables), so the
device search is unrolled. Root is by PARTUUID, unaffected by USB order.

The marker loads at the kernel address (0x04000000): the running script is
known not to live there, because the proven script already loads the kernel there.

usage: make-boot-cmds.py OUTDIR
"""
import sys
from pathlib import Path
MARK = '/tabor.id'  # 8.3 name: no reliance on VFAT long names
ROOT = 'root=PARTUUID=a1221115-02 rootfstype=ext4 rootwait rw init=/sbin/init console=ttyS0,115200 console=tty0'
KERNELS = {  # name -> (uImage, dtb, panic setting)
    '021': ('/boot/e2e-021/uImage', '/boot/e2e-021/tabor.dtb', 'panic=0'),
    '016': ('/boot/uImage', '/boot/tabor.dtb', 'panic=-1'),
}
def attempt(dev, k):
    img, dtb, panic = KERNELS[k]
    return (f' echo Tabor: kernel {k} from usb {dev}\n'
            f' if fatload usb {dev}:1 0x04000000 {img}; then\n'
            f'  if iminfo 0x04000000; then\n'
            f'   if fatload usb {dev}:1 0x08000000 {dtb}; then\n'
            f'    setenv bootargs {ROOT} {panic}\n'
            f'    bootm 0x04000000 - 0x08000000\n'
            f'   fi\n  fi\n fi\n')
def script(order, title):
    s = [f'# {title}\n# Generated by make-boot-cmds.py; USB is already initialized by the firmware.\n'
         f'# Finds the root stick by {MARK}, whichever USB number it got.\n']
    for dev in range(4):
        s.append(f'if fatload usb {dev}:1 0x04000000 {MARK}; then\n')
        for k in order:
            s.append(attempt(dev, k))
        s.append('fi\n')
    s.append('echo Tabor: no bootable kernel found on usb 0-3\n')
    return ''.join(s)
out = Path(sys.argv[1]); out.mkdir(parents=True, exist_ok=True)
(out / 'boot.cmd').write_text(script(['021', '016'], 'A1222 boot: kernel 021, falling back to 016 if 021 files are missing'))
(out / 'boot-016.cmd').write_text(script(['016'], 'A1222 boot: kernel 016 only (rollback)'))
(out / MARK.lstrip('/')).write_text('Tabor A1222 root stick: SanDisk Cruzer Glide, PARTUUID a1221115\n')
